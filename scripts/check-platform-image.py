def main():
    report={'schemaVersion':1,'scope':'company image CI; not native installation acceptance','suites':[]}
    path=Path('/app/company-ci-results.json')
    for original in COMMANDS:
        command=list(original);environment=os.environ.copy()
        environment['AUTOSOFT_TEST_ARTIFACT_ROOT']='/app/.local'
        if command[0]=='AUTOSOFT_TEST_ARTIFACT_ROOT=/tmp':
            command.pop(0)
        command=[item.replace('AUTOSOFT_TEST_ARTIFACT_ROOT=/tmp','AUTOSOFT_TEST_ARTIFACT_ROOT=/app/.local') for item in command]
        if command[:2]==['python3','scripts/test-company-release.py']:
            command=['python3','-I','-B',*command[1:]]
        assert command[0] in ('python3','node','env')
        started=time.monotonic()
        print(json.dumps({'companyCiSuite':command,'status':'running'}),flush=True)
        try:
            result=subprocess.run(command,env=environment,timeout=600)
            row={'command':command,'exitCode':result.returncode,'seconds':round(time.monotonic()-started,3)}
        except subprocess.TimeoutExpired:
            row={'command':command,'status':'timed_out','seconds':round(time.monotonic()-started,3)}
            report['suites'].append(row);path.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
            return 2
        report['suites'].append(row)
        path.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    failed=[row for row in report['suites'] if row.get('exitCode')!=0]
    print(json.dumps({'companyCiSuites':len(report['suites']),'failed':failed}),flush=True)
    return 1 if failed else 0

if __name__=='__main__':raise SystemExit(main())
